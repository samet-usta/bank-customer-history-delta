"""Gold dim_customer: SCD Type 2 customer dimension."""

from pyspark.sql import functions as F

import silver_transforms

BRONZE_SCHEMA = "workspace.bronze"
GOLD_TABLE = "workspace.gold.dim_customer"
BATCH_LOG_TABLE = "workspace.silver.batch_log"
DIM_NAME = "dim_customer"

INITIAL_VALID_FROM = "1993-01-01 00:00:00"
OPEN_VALID_TO = "9999-12-31 00:00:00"

CREATE_TABLE_SQL = f"""
CREATE OR REPLACE TABLE {GOLD_TABLE} (
    customer_sk   BIGINT GENERATED ALWAYS AS IDENTITY,
    client_id     INT,
    birth_date    DATE,
    gender        STRING,
    district_id   INT,
    district_name STRING,
    region        STRING,
    row_hash      STRING,
    valid_from    TIMESTAMP,
    valid_to      TIMESTAMP,
    is_current    BOOLEAN
)
"""

# customer_sk is generated by IDENTITY, so it is not in the insert list
INSERT_COLUMNS = (
    "client_id, birth_date, gender, district_id, district_name, region, "
    "row_hash, valid_from, valid_to, is_current"
)


def read_district(spark):
    """District lookup: A1 -> district_id, A2 -> district_name, A3 -> region."""
    df_district = spark.table(f"{BRONZE_SCHEMA}.district")
    df_district = df_district.select(
        F.col("A1").cast("int").alias("district_id"),
        F.col("A2").alias("district_name"),
        F.col("A3").alias("region"),
    )
    return df_district


def add_customer_attributes(df_client, df_district):
    """Add birth_date, gender, district attributes and row_hash to silver-typed client rows."""
    # birth_number: YYMMDD for men, YYMM+50DD for women
    birth_year = F.lit(1900) + F.substring("birth_number", 1, 2).cast("int")
    birth_month_raw = F.substring("birth_number", 3, 2).cast("int")
    birth_day = F.substring("birth_number", 5, 2).cast("int")
    is_female = birth_month_raw > 50
    birth_month = F.when(is_female, birth_month_raw - 50).otherwise(birth_month_raw)

    df = df_client.withColumn("birth_date", F.make_date(birth_year, birth_month, birth_day))
    df = df.withColumn("gender", F.when(is_female, "F").otherwise("M"))
    df = df.join(df_district, on="district_id", how="left")

    # hash of the SCD2 tracked columns
    tracked_values = F.concat_ws(
        "||",
        F.col("district_id").cast("string"),
        F.col("district_name"),
        F.col("region"),
    )
    df = df.withColumn("row_hash", F.sha2(tracked_values, 256))
    return df


def load_initial(spark):
    """Recreate dim_customer from the bronze client snapshot (before any CDC batch)."""
    spark.sql(CREATE_TABLE_SQL)

    df_bronze_client = spark.table(f"{BRONZE_SCHEMA}.client")
    df_client = silver_transforms.to_silver(df_bronze_client, "client")
    df_district = read_district(spark)
    df_initial = add_customer_attributes(df_client, df_district)

    df_initial = df_initial.withColumn("valid_from", F.to_timestamp(F.lit(INITIAL_VALID_FROM)))
    df_initial = df_initial.withColumn("valid_to", F.to_timestamp(F.lit(OPEN_VALID_TO)))
    df_initial = df_initial.withColumn("is_current", F.lit(True))
    df_initial.createOrReplaceTempView("vw_dim_customer_initial")

    spark.sql(
        f"INSERT INTO {GOLD_TABLE} ({INSERT_COLUMNS}) "
        f"SELECT {INSERT_COLUMNS} FROM vw_dim_customer_initial"
    )

    # dim batches must run again after a reset
    spark.sql(f"DELETE FROM {BATCH_LOG_TABLE} WHERE table_name = '{DIM_NAME}'")